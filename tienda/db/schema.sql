-- Cafetería Andina · esquema PostgreSQL (Supabase)
create table categorias (
  id bigint generated by default as identity primary key,
  nombre text not null unique,
  descripcion text
);
create table proveedores (
  id bigint generated by default as identity primary key,
  nombre text not null,
  ciudad text not null,
  telefono text,
  creado_en timestamptz not null default now()
);
create table productos (
  id bigint generated by default as identity primary key,
  categoria_id bigint not null references categorias(id) on delete restrict on update cascade,
  proveedor_id bigint references proveedores(id) on delete set null on update cascade,
  nombre text not null,
  precio numeric(10,2) not null check (precio >= 0),
  stock int not null default 0 check (stock >= 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);
create table clientes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  email text not null unique,
  ciudad text not null,
  creado_en timestamptz not null default now()
);
create table empleados (
  id bigint generated by default as identity primary key,
  nombre text not null,
  cargo text not null,
  email text not null unique,
  activo boolean not null default true
);
create table pedidos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references clientes(id) on delete restrict on update cascade,
  empleado_id bigint references empleados(id) on delete set null on update cascade,
  estado text not null default 'pendiente' check (estado in ('pendiente','preparando','entregado','cancelado')),
  canal text not null check (canal in ('local','domicilio','web')),
  creado_en timestamptz not null default now()
);
create table detalle_pedidos (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references pedidos(id) on delete cascade on update cascade,
  producto_id bigint not null references productos(id) on delete restrict on update cascade,
  cantidad int not null check (cantidad > 0),
  precio_unitario numeric(10,2) not null check (precio_unitario >= 0)
);
create table pagos (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references pedidos(id) on delete cascade on update cascade,
  metodo text not null check (metodo in ('efectivo','tarjeta','nequi','daviplata')),
  monto numeric(12,2) not null check (monto >= 0),
  pagado_en timestamptz not null default now()
);
create table logs_auditoria (
  id bigint generated by default as identity primary key,
  tabla text not null,
  accion text not null,
  registro_id bigint,
  detalle jsonb,
  creado_en timestamptz not null default now()
);
create table metricas_uso (
  id bigint generated by default as identity primary key,
  fecha date not null,
  canal text not null check (canal in ('local','domicilio','web')),
  visitas int not null default 0,
  pedidos_creados int not null default 0,
  unique (fecha, canal)
);

create index idx_productos_categoria on productos(categoria_id);
create index idx_productos_proveedor on productos(proveedor_id);
create index idx_pedidos_cliente on pedidos(cliente_id);
create index idx_pedidos_creado on pedidos(creado_en);
create index idx_pedidos_estado on pedidos(estado);
create index idx_detalle_pedido on detalle_pedidos(pedido_id);
create index idx_detalle_producto on detalle_pedidos(producto_id);
create index idx_pagos_pedido on pagos(pedido_id);
create index idx_logs_creado on logs_auditoria(creado_en);

-- Auditoría automática de pedidos
create or replace function fn_audit_pedidos() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into logs_auditoria(tabla, accion, registro_id, detalle)
  values ('pedidos', tg_op,
          coalesce(new.id, old.id),
          to_jsonb(coalesce(new, old)));
  return coalesce(new, old);
end $$;
create trigger trg_audit_pedidos after insert or update or delete on pedidos
for each row execute function fn_audit_pedidos();

-- Vista plana para Looker Studio
create view v_ventas as
select dp.id as detalle_id, p.id as pedido_id, p.creado_en::date as fecha,
       p.estado, p.canal, c.nombre as cliente, c.ciudad,
       pr.nombre as producto, cat.nombre as categoria,
       dp.cantidad, dp.precio_unitario,
       dp.cantidad * dp.precio_unitario as total_linea
from detalle_pedidos dp
join pedidos p on p.id = dp.pedido_id
join clientes c on c.id = p.cliente_id
join productos pr on pr.id = dp.producto_id
join categorias cat on cat.id = pr.categoria_id;

-- Acceso desde la app (clave anon). Política abierta SOLO para demo académica.
do $$
declare t text;
begin
  foreach t in array array['categorias','proveedores','productos','clientes','empleados',
                           'pedidos','detalle_pedidos','pagos','logs_auditoria','metricas_uso']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy demo_all on %I for all to anon using (true) with check (true)', t);
  end loop;
end $$;
grant select on v_ventas to anon;
